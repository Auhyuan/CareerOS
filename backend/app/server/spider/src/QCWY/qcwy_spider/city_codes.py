def resolve_city_code(city_or_code):
    """把城市名称转换成前程无忧城市编码；如果传入的本来就是编码，则直接返回。"""
    value = str(city_or_code).strip()
    if value.isdigit():
        return value
    return CITY_CODE_MAP.get(value, value)
